-- I09 · view, materialized view, function, trigger. Chạy trên DB `lab`, schema `i09`. Chạy lại bao nhiêu lần cũng được (reset về ban đầu).
DROP SCHEMA IF EXISTS i09 CASCADE;
CREATE SCHEMA i09;

CREATE TABLE i09.customers (
  id     int PRIMARY KEY,
  name   text NOT NULL,
  email  text NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'blocked'))
);
