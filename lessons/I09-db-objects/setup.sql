CREATE TABLE i09.orders (
  id          int PRIMARY KEY,
  customer_id int NOT NULL REFERENCES i09.customers(id),
  status      text NOT NULL,
  total       numeric(12,2) NOT NULL,
  created_at  timestamptz NOT NULL
);
-- 12 đơn cố định: đơn i của khách 1 + (i % 5), tổng i × 150 000, trạng thái xoay vòng, mỗi đơn cách nhau 9 giờ từ 2026-09-01 00:00+07
INSERT INTO i09.orders
SELECT i, 1 + (i % 5), (ARRAY['delivered', 'paid', 'cancelled', 'delivered'])[1 + (i % 4)], i * 150000,
       timestamptz '2026-09-01 00:00+07' + i * interval '9 hours'
FROM generate_series(1, 12) i;

CREATE TABLE i09.order_lines (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   int NOT NULL REFERENCES i09.orders(id),
  product_id int NOT NULL REFERENCES i09.products(id),
  quantity   int NOT NULL CHECK (quantity > 0)
);

CREATE TABLE i09.price_history (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id int NOT NULL,
  old_price  numeric(12,2) NOT NULL,
  new_price  numeric(12,2) NOT NULL,
  changed_at timestamptz NOT NULL DEFAULT now()
);

-- ex08: một view đang chạy ở production và một view phụ thuộc vào nó
CREATE VIEW i09.v_order_summary AS
SELECT o.id AS order_id, c.name AS customer_name, o.total
FROM i09.orders o JOIN i09.customers c ON c.id = o.customer_id;
CREATE VIEW i09.v_big_orders AS
SELECT order_id, customer_name FROM i09.v_order_summary WHERE total >= 900000;
