CREATE TABLE f09.promotions (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text NOT NULL UNIQUE,
  percent int, amount numeric(12,2), starts_at timestamptz NOT NULL, ends_at timestamptz,
  CHECK ((percent IS NOT NULL AND amount IS NULL AND percent BETWEEN 1 AND 90)
      OR (percent IS NULL AND amount IS NOT NULL AND amount > 0)),
  CHECK (ends_at IS NULL OR ends_at > starts_at));
