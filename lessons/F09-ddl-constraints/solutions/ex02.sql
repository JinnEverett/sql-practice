-- Giải thích: regex phải neo đầu ^ và cuối $, nếu không 'XAB-00011' vẫn "chứa" mẫu và lọt qua.
--   Dùng CHECK (status IN (...)) cho tập giá trị nhỏ, ít đổi. (Tập lớn hoặc hay đổi thì dùng bảng tra + FK.)
-- Bẫy: CHECK (sku ~ '[A-Z]{2}-[0-9]{4}') thiếu ^…$; quên NOT NULL ở cột có CHECK (CHECK cho NULL đi qua).
CREATE TABLE f09.products (
  id     int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku    text NOT NULL UNIQUE CHECK (sku ~ '^[A-Z]{2}-[0-9]{4}$'),
  name   text NOT NULL,
  price  numeric(12,2) NOT NULL CHECK (price >= 0),
  stock  int NOT NULL DEFAULT 0 CHECK (stock >= 0),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'archived'))
);
