-- Giải thích: partial unique index: UNIQUE chỉ áp lên các dòng thỏa WHERE. Dòng is_default = false nằm ngoài index nên
--   không bị giới hạn. Đây là cách chuẩn cho các luật "tối đa một X đang hoạt động mỗi Y".
-- Bẫy: UNIQUE (user_id, is_default) chặn luôn địa chỉ thường thứ hai (cặp (1, false) trùng).
CREATE TABLE f09.addresses (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    int NOT NULL,
  line       text NOT NULL,
  is_default boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX addresses_one_default_per_user ON f09.addresses (user_id) WHERE is_default;
