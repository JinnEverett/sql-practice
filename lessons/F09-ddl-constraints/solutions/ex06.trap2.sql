CREATE TABLE f09.promotions (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text NOT NULL UNIQUE,
  percent int CHECK (percent BETWEEN 1 AND 90), amount numeric(12,2) CHECK (amount > 0),
  starts_at timestamptz NOT NULL, ends_at timestamptz,
  CHECK (num_nonnulls(percent, amount) = 1), CHECK (ends_at >= starts_at));
