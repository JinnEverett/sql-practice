CREATE TABLE f09.c_orders (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int NOT NULL REFERENCES f09.c_customers (id), created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE f09.c_order_items (order_id int NOT NULL REFERENCES f09.c_orders (id) ON DELETE CASCADE, line_no smallint NOT NULL,
  product_id int NOT NULL REFERENCES f09.c_products (id), quantity int NOT NULL CHECK (quantity > 0), PRIMARY KEY (order_id, line_no));
