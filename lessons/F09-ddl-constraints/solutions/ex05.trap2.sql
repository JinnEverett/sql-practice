CREATE TABLE f09.order_lines (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, quantity int NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  discount_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
  line_total numeric(14,2) GENERATED ALWAYS AS (trunc(quantity * unit_price * (1 - discount_pct / 100), 0)) STORED);
