-- Giải thích:
--   * Tên không phân biệt hoa/thường: unique index trên lower(name).
--   * Chống chồng giờ: EXCLUDE USING gist (room_id WITH =, tstzrange(starts_at, ends_at) WITH &&). Hai dòng "xung đột" khi
--     cùng phòng VÀ khoảng thời gian giao nhau. tstzrange mặc định là '[)' (gồm đầu, không gồm cuối) nên 9–10 và 10–11 không giao.
--     `room_id WITH =` trong gist cần extension btree_gist (setup đã tạo).
--   * WHERE (status = 'confirmed') biến nó thành exclusion constraint một phần: lịch đã hủy không tham gia.
-- Bẫy: thiếu WHERE (lịch hủy vẫn chặn); dùng '[]' (chặn lịch nối tiếp); UNIQUE (name) phân biệt hoa/thường.
--   Kiểm tra chồng giờ bằng code ứng dụng (SELECT rồi INSERT) không an toàn khi 2 request chạy song song (xem R08).
CREATE TABLE f09.rooms (
  id   int PRIMARY KEY,
  name text NOT NULL
);
CREATE UNIQUE INDEX rooms_name_ci_key ON f09.rooms (lower(name));

CREATE TABLE f09.bookings (
  id        int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id   int NOT NULL REFERENCES f09.rooms (id),
  booked_by text NOT NULL,
  starts_at timestamptz NOT NULL,
  ends_at   timestamptz NOT NULL,
  status    text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed', 'cancelled')),
  CHECK (ends_at > starts_at),
  EXCLUDE USING gist (room_id WITH =, tstzrange(starts_at, ends_at) WITH &&) WHERE (status = 'confirmed')
);
