CREATE TABLE f09.rooms (id int PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE f09.bookings (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_id int NOT NULL REFERENCES f09.rooms (id),
  booked_by text NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed', 'cancelled')), CHECK (ends_at > starts_at),
  EXCLUDE USING gist (room_id WITH =, tstzrange(starts_at, ends_at) WITH &&) WHERE (status = 'confirmed'));
