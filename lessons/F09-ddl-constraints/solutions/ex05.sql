-- Giải thích: GENERATED ALWAYS AS (biểu thức) STORED tính khi INSERT/UPDATE và lưu xuống đĩa. Biểu thức phải IMMUTABLE
--   (không dùng now(), không tham chiếu bảng khác). Postgres 18 có thêm VIRTUAL (tính lúc đọc, là mặc định nếu không ghi STORED).
--   discount_pct là numeric nên discount_pct / 100 không bị chia nguyên.
-- Bẫy: để line_total là cột thường (ứng dụng ghi sai được, đổi quantity không cập nhật); trunc thay cho round.
CREATE TABLE f09.order_lines (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quantity     int NOT NULL CHECK (quantity > 0),
  unit_price   numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  discount_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
  line_total   numeric(14,2) GENERATED ALWAYS AS (round(quantity * unit_price * (1 - discount_pct / 100), 2)) STORED
);
