-- cách khác: upper() thay lower(), CHECK = ANY(ARRAY), ghi rõ cận [), WHERE status <> 'cancelled'
CREATE TABLE f09.rooms (id int PRIMARY KEY, name text NOT NULL);
CREATE UNIQUE INDEX ON f09.rooms (upper(name));
CREATE TABLE f09.bookings (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_id int NOT NULL REFERENCES f09.rooms,
  booked_by text NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'confirmed', CONSTRAINT status_ok CHECK (status = ANY (ARRAY['confirmed', 'cancelled'])),
  CONSTRAINT time_ok CHECK (starts_at < ends_at),
  CONSTRAINT no_overlap EXCLUDE USING gist (room_id WITH =, tstzrange(starts_at, ends_at, '[)') WITH &&) WHERE (status <> 'cancelled'));
