-- Giải thích: ON DELETE mặc định là NO ACTION (gần như RESTRICT): chặn xóa cha khi còn con. Dòng hàng là "một phần" của đơn
--   nên dùng ON DELETE CASCADE. Về index: c_order_items(order_id) đã được PK (order_id, line_no) phủ vì là cột ĐẦU của PK;
--   còn thiếu c_orders(customer_id) và c_order_items(product_id). Thiếu index FK thì mỗi lần xóa/sửa khóa ở bảng cha,
--   Postgres phải quét cả bảng con để kiểm tra → chậm và giữ lock lâu.
-- Bẫy: ON DELETE CASCADE cho customer (xóa khách là mất sạch lịch sử đơn); quên index FK; tạo index thừa trên order_id.
CREATE TABLE f09.c_orders (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int NOT NULL REFERENCES f09.c_customers (id) ON DELETE RESTRICT,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE f09.c_order_items (
  order_id   int NOT NULL REFERENCES f09.c_orders (id) ON DELETE CASCADE,
  line_no    smallint NOT NULL,
  product_id int NOT NULL REFERENCES f09.c_products (id),
  quantity   int NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (order_id, line_no)
);
CREATE INDEX ON f09.c_orders (customer_id);
CREATE INDEX ON f09.c_order_items (product_id);
