-- Giải thích: CHECK nhiều cột viết ở mức bảng. num_nonnulls(a, b) = 1 diễn đạt "đúng một trong hai".
--   CHECK cho qua khi biểu thức ra NULL. Ở đây đó lại là điều ta muốn: ends_at NULL → (ends_at > starts_at) là NULL → hợp lệ;
--   percent NULL → CHECK (percent BETWEEN 1 AND 90) là NULL → hợp lệ.
-- Bẫy: CHECK (percent IS NULL OR amount IS NULL) chỉ chặn "cả hai", vẫn cho "không có cái nào"; dùng >= cho ends_at.
CREATE TABLE f09.promotions (
  id        int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      text NOT NULL UNIQUE,
  percent   int CHECK (percent BETWEEN 1 AND 90),
  amount    numeric(12,2) CHECK (amount > 0),
  starts_at timestamptz NOT NULL,
  ends_at   timestamptz,
  CHECK (num_nonnulls(percent, amount) = 1),
  CHECK (ends_at > starts_at)
);
