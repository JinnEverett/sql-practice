-- Tham số: số dòng của events_p, mặc định 60 000. Đổi bằng:  psql -v n=1000000 -f setup.sql
\if :{?n}
\else
\set n 60000
\endif
DROP SCHEMA IF EXISTS r12 CASCADE;
CREATE SCHEMA r12;

-- (1) events_p: partition theo tháng UTC, 6 tháng đầu 2026 (ex02, ex05, ex06, ex08)
CREATE TABLE r12.events_p (
  id     bigint GENERATED BY DEFAULT AS IDENTITY,
  device int NOT NULL,
  ts     timestamptz NOT NULL,
  value  numeric(10,2) NOT NULL,
  PRIMARY KEY (id, ts)
) PARTITION BY RANGE (ts);
CREATE TABLE r12.events_p_2026_01 PARTITION OF r12.events_p FOR VALUES FROM ('2026-01-01 00:00+00') TO ('2026-02-01 00:00+00');
CREATE TABLE r12.events_p_2026_02 PARTITION OF r12.events_p FOR VALUES FROM ('2026-02-01 00:00+00') TO ('2026-03-01 00:00+00');
CREATE TABLE r12.events_p_2026_03 PARTITION OF r12.events_p FOR VALUES FROM ('2026-03-01 00:00+00') TO ('2026-04-01 00:00+00');
CREATE TABLE r12.events_p_2026_04 PARTITION OF r12.events_p FOR VALUES FROM ('2026-04-01 00:00+00') TO ('2026-05-01 00:00+00');
CREATE TABLE r12.events_p_2026_05 PARTITION OF r12.events_p FOR VALUES FROM ('2026-05-01 00:00+00') TO ('2026-06-01 00:00+00');
CREATE TABLE r12.events_p_2026_06 PARTITION OF r12.events_p FOR VALUES FROM ('2026-06-01 00:00+00') TO ('2026-07-01 00:00+00');
INSERT INTO r12.events_p (device, ts, value)
SELECT i % 50, timestamptz '2026-01-01 00:00+00' + (i::bigint * 181 * 86400 / :n) * interval '1 second', (i % 1000) / 10.0
FROM generate_series(0, :n - 1) i;
CREATE INDEX events_p_device_ts_idx ON r12.events_p (device, ts);
ANALYZE r12.events_p;

-- (2) legacy_events: bảng thường chứa dữ liệu tháng 7/2026, có cùng cấu trúc và PK (id, ts); muốn gắn vào events_p (ex06)
CREATE TABLE r12.legacy_events (
  id     bigint NOT NULL,
  device int NOT NULL,
  ts     timestamptz NOT NULL,
  value  numeric(10,2) NOT NULL,
  PRIMARY KEY (id, ts));
INSERT INTO r12.legacy_events
SELECT 1000000 + i, i % 50, timestamptz '2026-07-01 00:00+00' + (i::bigint * 31 * 86400 / 5000) * interval '1 second', (i % 1000) / 10.0
FROM generate_series(0, 4999) i;

-- (3) Rollup theo ngày (ex07): dữ liệu thô theo giờ và bảng tổng hợp theo ngày, trong đó có một dòng cũ bị sai
CREATE TABLE r12.metrics_raw (sensor int NOT NULL, ts timestamptz NOT NULL, value numeric(10,2) NOT NULL, PRIMARY KEY (sensor, ts));
INSERT INTO r12.metrics_raw
SELECT s, timestamptz '2026-03-01 00:00+07' + h * interval '1 hour', 10 + s + (h % 24)
FROM generate_series(1, 2) s, generate_series(0, 71) h;
CREATE TABLE r12.metrics_daily (
  sensor int NOT NULL, day date NOT NULL,
  n int NOT NULL, sum_value numeric(14,2) NOT NULL, min_value numeric(10,2) NOT NULL, max_value numeric(10,2) NOT NULL,
  PRIMARY KEY (sensor, day));
