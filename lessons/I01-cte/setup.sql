CREATE SCHEMA i01;

CREATE TABLE i01.orders (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    int NOT NULL,
  status     text NOT NULL,
  created_at timestamptz NOT NULL,
  total      numeric(12,2) NOT NULL
);
