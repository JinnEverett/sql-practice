-- D04 · Banking ledger: double-entry, số dư, chuyển tiền idempotent, đối soát. DB: lab, schema d04.
DROP SCHEMA IF EXISTS d04 CASCADE;
CREATE SCHEMA d04;
SET search_path = d04;

CREATE TABLE accounts (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    owner_ref      text,                                   -- NULL với tài khoản hệ thống
    currency       char(3) NOT NULL DEFAULT 'VND',
    created_at     timestamptz NOT NULL DEFAULT now()
);

-- Số dư hiện tại: bản sao có thể dựng lại từ entries. Một dòng/tài khoản, cập nhật cùng transaction với entries.
CREATE TABLE account_balances (
    account_id bigint PRIMARY KEY REFERENCES accounts(id),
    balance    bigint NOT NULL,                            -- đơn vị nhỏ nhất (VND không có xu; USD = cent). KHÔNG float.
    allow_negative boolean NOT NULL DEFAULT false,         -- chỉ tài khoản hệ thống (nguồn tiền, phí) được âm
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT balance_non_negative CHECK (balance >= 0 OR allow_negative)   -- chống thấu chi ngay ở DB
) WITH (fillfactor = 80);

CREATE TABLE transactions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key text   NOT NULL,
    request_hash    text   NOT NULL,                       -- hash (from,to,amount): cùng key khác nội dung = lỗi client
    kind            text   NOT NULL CHECK (kind IN ('transfer','funding','reversal','fee')),
    reverses_id     bigint REFERENCES transactions(id),    -- giao dịch bù trừ trỏ về giao dịch gốc
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT transactions_idem_uk UNIQUE (idempotency_key)
);
CREATE UNIQUE INDEX transactions_reverses_uk ON transactions (reverses_id) WHERE reverses_id IS NOT NULL;   -- hoàn 1 lần duy nhất

-- Sổ cái: append-only. Phân vùng theo tháng để retention/lưu trữ không cần DELETE.
CREATE TABLE entries (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    txn_id        bigint NOT NULL REFERENCES transactions(id),
    account_id    bigint NOT NULL REFERENCES accounts(id),
    amount        bigint NOT NULL CHECK (amount <> 0),     -- có dấu: + ghi có (nhận), − ghi nợ (trả)
    balance_after bigint NOT NULL,                         -- số dư chạy: sao kê không cần window function
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE TABLE entries_2026_09 PARTITION OF entries FOR VALUES FROM ('2026-09-01') TO ('2026-10-01');
CREATE TABLE entries_2026_10 PARTITION OF entries FOR VALUES FROM ('2026-10-01') TO ('2026-11-01');
CREATE TABLE entries_2026_11 PARTITION OF entries FOR VALUES FROM ('2026-11-01') TO ('2026-12-01');
CREATE INDEX entries_account_idx ON entries (account_id, created_at DESC, id DESC);   -- sao kê + keyset pagination
CREATE INDEX entries_txn_idx ON entries (txn_id);

-- Bất biến 1: sổ cái không sửa, không xóa
CREATE FUNCTION entries_immutable() RETURNS trigger LANGUAGE plpgsql SET search_path = d04 AS $$
BEGIN RAISE EXCEPTION 'entries là append-only; muốn sửa hãy tạo giao dịch bù trừ' USING ERRCODE = 'restrict_violation'; END $$;
CREATE TRIGGER entries_no_update BEFORE UPDATE OR DELETE ON entries FOR EACH ROW EXECUTE FUNCTION entries_immutable();

-- Bất biến 2: mỗi giao dịch có tổng amount = 0 (kiểm lúc COMMIT nhờ DEFERRABLE INITIALLY DEFERRED)
CREATE FUNCTION entries_balanced() RETURNS trigger LANGUAGE plpgsql SET search_path = d04 AS $$
BEGIN
    IF (SELECT sum(amount) FROM entries WHERE txn_id = NEW.txn_id) <> 0 THEN
        RAISE EXCEPTION 'giao dịch % không cân (tổng entries <> 0)', NEW.txn_id USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER entries_balanced_ct AFTER INSERT ON entries
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION entries_balanced();

-- Chuyển tiền: idempotent, khóa số dư theo thứ tự id, ghi 2 entries cùng balance_after.
-- Trả về txn_id. Cùng key + cùng nội dung => trả giao dịch cũ. Cùng key + khác nội dung => lỗi.
CREATE FUNCTION transfer(p_key text, p_from bigint, p_to bigint, p_amount bigint) RETURNS bigint
LANGUAGE plpgsql SET search_path = d04 AS $$
DECLARE
    v_hash text := md5(p_from || ':' || p_to || ':' || p_amount);
    v_txn bigint; v_old_hash text; v_from_bal bigint; v_to_bal bigint;
BEGIN
    IF p_amount <= 0 OR p_from = p_to THEN RAISE EXCEPTION 'tham số không hợp lệ' USING ERRCODE = 'invalid_parameter_value'; END IF;
    INSERT INTO transactions (idempotency_key, request_hash, kind) VALUES (p_key, v_hash, 'transfer')
    ON CONFLICT (idempotency_key) DO NOTHING RETURNING id INTO v_txn;
    IF v_txn IS NULL THEN
        SELECT id, request_hash INTO v_txn, v_old_hash FROM transactions WHERE idempotency_key = p_key;
        IF v_old_hash <> v_hash THEN RAISE EXCEPTION 'idempotency key % đã dùng cho yêu cầu khác', p_key USING ERRCODE = 'unique_violation'; END IF;
        RETURN v_txn;
    END IF;
    -- Khóa theo thứ tự id tăng dần: A→B và B→A cùng lúc không deadlock
    PERFORM 1 FROM account_balances WHERE account_id IN (p_from, p_to) ORDER BY account_id FOR UPDATE;
    UPDATE account_balances SET balance = balance - p_amount, updated_at = now() WHERE account_id = p_from RETURNING balance INTO v_from_bal;  -- CHECK chặn thấu chi
    UPDATE account_balances SET balance = balance + p_amount, updated_at = now() WHERE account_id = p_to   RETURNING balance INTO v_to_bal;
    INSERT INTO entries (txn_id, account_id, amount, balance_after) VALUES
        (v_txn, p_from, -p_amount, v_from_bal), (v_txn, p_to, p_amount, v_to_bal);
    RETURN v_txn;
END $$;

-- Phiên bản NGÂY THƠ (chỉ để thí nghiệm concurrency): không sắp thứ tự khóa => deadlock
CREATE FUNCTION transfer_naive(p_key text, p_from bigint, p_to bigint, p_amount bigint) RETURNS bigint
LANGUAGE plpgsql SET search_path = d04 AS $$
DECLARE v_txn bigint; v_f bigint; v_t bigint;
BEGIN
    INSERT INTO transactions (idempotency_key, request_hash, kind) VALUES (p_key, '-', 'transfer') RETURNING id INTO v_txn;
    UPDATE account_balances SET balance = balance - p_amount WHERE account_id = p_from RETURNING balance INTO v_f;
    PERFORM pg_sleep(0.001);                                   -- mô phỏng xử lý giữa hai bước
    UPDATE account_balances SET balance = balance + p_amount WHERE account_id = p_to RETURNING balance INTO v_t;
    INSERT INTO entries (txn_id, account_id, amount, balance_after) VALUES (v_txn, p_from, -p_amount, v_f), (v_txn, p_to, p_amount, v_t);
    RETURN v_txn;
END $$;

-- Hoàn giao dịch = giao dịch mới đảo dấu (không sửa lịch sử). Chỉ hoàn được 1 lần (transactions_reverses_uk).
CREATE FUNCTION reverse_transfer(p_key text, p_txn bigint) RETURNS bigint
LANGUAGE plpgsql SET search_path = d04 AS $$
DECLARE v_new bigint; v_bal bigint; r record;
BEGIN
    INSERT INTO transactions (idempotency_key, request_hash, kind, reverses_id) VALUES (p_key, 'rev:' || p_txn, 'reversal', p_txn)
    RETURNING id INTO v_new;                                   -- vi phạm unique nếu đã hoàn
    PERFORM 1 FROM account_balances WHERE account_id IN (SELECT account_id FROM entries WHERE txn_id = p_txn) ORDER BY account_id FOR UPDATE;
    FOR r IN SELECT account_id, -amount AS amt FROM entries WHERE txn_id = p_txn ORDER BY account_id LOOP
        UPDATE account_balances SET balance = balance + r.amt, updated_at = now() WHERE account_id = r.account_id RETURNING balance INTO v_bal;
        INSERT INTO entries (txn_id, account_id, amount, balance_after) VALUES (v_new, r.account_id, r.amt, v_bal);
    END LOOP;
    RETURN v_new;
END $$;

