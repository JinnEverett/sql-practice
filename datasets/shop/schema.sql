-- Schema e-commerce "shop".
-- Chỉ có PRIMARY KEY. FK / CHECK / UNIQUE được thêm SAU khi nạp dữ liệu (constraints.sql),
-- đúng cách người ta nạp dữ liệu lớn ngoài đời.
-- KHÔNG có index phụ: các bài học sẽ tự quyết định index nào cần.

CREATE TABLE categories (
  id        integer PRIMARY KEY,
  parent_id integer,                 -- NULL = danh mục gốc (cây 3 tầng)
  name      text NOT NULL,
  slug      text NOT NULL
);

CREATE TABLE users (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      text NOT NULL,
  full_name  text,
  phone      text,
  birth_date date,
  country    char(2) NOT NULL,       -- ISO 3166-1 alpha-2
  city       text,
  created_at timestamptz NOT NULL,
  deleted_at timestamptz             -- soft delete
);

CREATE TABLE products (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL,
  sku         text NOT NULL,
  name        text NOT NULL,
  brand       text,
  price       numeric(12,2) NOT NULL, -- VND
  stock       integer NOT NULL,
  attributes  jsonb NOT NULL DEFAULT '{}',
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL
);

CREATE TABLE orders (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         bigint NOT NULL,
  status          text NOT NULL,     -- pending | paid | shipped | delivered | cancelled | refunded
  discount_code   text,
  shipping_fee    numeric(12,2) NOT NULL DEFAULT 0,
  discount_amount numeric(12,2) NOT NULL DEFAULT 0,
  total_amount    numeric(12,2) NOT NULL, -- = sum(items) + shipping_fee - discount_amount
  created_at      timestamptz NOT NULL,
  updated_at      timestamptz NOT NULL
);

CREATE TABLE order_items (
  order_id   bigint NOT NULL,
  line_no    smallint NOT NULL,
  product_id bigint NOT NULL,
  quantity   integer NOT NULL,
  unit_price numeric(12,2) NOT NULL,  -- giá lúc mua, có thể khác products.price hiện tại
  PRIMARY KEY (order_id, line_no)
);

CREATE TABLE payments (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   bigint NOT NULL,
  method     text NOT NULL,           -- card | ewallet | bank_transfer | cod
  status     text NOT NULL,           -- succeeded | failed | refunded
  amount     numeric(12,2) NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE events (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      bigint,                -- NULL = khách chưa đăng nhập
  anonymous_id text,
  event_type   text NOT NULL,         -- page_view | product_view | search | add_to_cart | checkout
  properties   jsonb NOT NULL DEFAULT '{}',
  created_at   timestamptz NOT NULL
);
